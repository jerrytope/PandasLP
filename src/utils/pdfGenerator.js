import { jsPDF } from 'jspdf'

function formatValue(field, value) {
  if (field.type === 'file') {
    return value && value.name ? `Attached: ${value.name}` : 'Not provided'
  }
  if (value === undefined || value === null || value === '') return 'Not provided'
  if (field.type === 'number' && field.name.toLowerCase().includes('amount')) {
    return `₦${Number(value).toLocaleString()}`
  }
  return String(value)
}

export function buildDocument(service, formData) {
  const doc = new jsPDF({ unit: 'pt', format: 'a4' })
  const marginX = 56
  let y = 64

  doc.setFont('helvetica', 'bold')
  doc.setFontSize(18)
  doc.text('Pandas LP', marginX, y)
  doc.setFontSize(10)
  doc.setFont('helvetica', 'normal')
  doc.text('Professional Legal Services, Powered by AI', marginX, y + 16)

  y += 48
  doc.setDrawColor(230, 57, 70)
  doc.setLineWidth(1.2)
  doc.line(marginX, y, 540, y)

  y += 32
  doc.setFontSize(15)
  doc.setFont('helvetica', 'bold')
  doc.text(service.title, marginX, y)

  if (service.forms?.length) {
    y += 18
    doc.setFontSize(10)
    doc.setFont('helvetica', 'italic')
    doc.text(`Reference Forms: ${service.forms.join(', ')}`, marginX, y)
  }

  y += 30
  doc.setFont('helvetica', 'normal')
  doc.setFontSize(11)

  for (const field of service.fields) {
    const value = formatValue(field, formData[field.name])
    const lines = doc.splitTextToSize(`${field.label}: ${value}`, 480)
    if (y + lines.length * 14 > 760) {
      doc.addPage()
      y = 64
    }
    doc.text(lines, marginX, y)
    y += lines.length * 14 + 8
  }

  y += 24
  if (y > 740) {
    doc.addPage()
    y = 64
  }
  doc.setFontSize(8)
  doc.setTextColor(120)
  doc.text(
    doc.splitTextToSize(
      'This document was generated by Pandas LP based on information you provided and is intended to assist with self-filing. It does not constitute legal advice. For complex matters, consult a licensed legal practitioner.',
      480,
    ),
    marginX,
    y,
  )

  return doc
}

export function generatePdfBlobUrl(service, formData) {
  const doc = buildDocument(service, formData)
  return doc.output('bloburl')
}

export function downloadPdf(service, formData) {
  const doc = buildDocument(service, formData)
  const filename = `${service.id}-${Date.now()}.pdf`
  doc.save(filename)
}
